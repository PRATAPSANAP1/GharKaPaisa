/**
 * applicationCache.service.js
 * ──────────────────────────────────────────────────────────────────────────
 * Scoped caching and invalidation service for GET /api/v1/applications.
 * 
 * Safety & Architecture Highlights:
 * 1. Strict Scope Isolation: Every cache key is scoped to req.user.id and role.
 * 2. Zero PII in Keys: Customer search terms (mobile, PAN, name) are hashed (SHA-256).
 * 3. Bounded Latency: Cache operations have strict timeout bounds (250ms).
 * 4. Fault Tolerant: Redis/cache failures gracefully fall back to PostgreSQL.
 * 5. Deterministic Normalization: Query params are canonicalized and hashed.
 * 6. Post-Commit Invalidation: Invalidation triggers execute after successful DB writes.
 * 7. Non-blocking Invalidation: Cache errors never break write responses.
 */

const crypto = require('crypto');
const cache = require('./cache.service');
const logger = require('../config/logger');

// Default TTL: 60 seconds (1 minute) for interactive CRM application queues
const DEFAULT_APPLICATIONS_CACHE_TTL = 60;

/**
 * Builds a deterministic, PII-free, strictly scoped cache key for GET /api/v1/applications
 * 
 * Format:
 * app_list:{ROLE}:{USER_ID}:{PARAM_HASH}
 * 
 * @param {Object} req Express request containing req.user
 * @param {Object} queryParams Extracted and validated query parameters
 * @returns {string} Fully qualified cache key
 */
function buildApplicationListCacheKey(req, queryParams = {}) {
  const userId = req.user?.id || 'anonymous';
  const role = (req.user?.role || 'UNKNOWN').toUpperCase();
  const designation = (req.user?.designation || '').toUpperCase();

  // Hash search term with SHA-256 to ensure no customer PII (phone, PAN, name)
  // is placed in cache keys, Redis key logs, or memory keyspaces.
  const rawSearch = (queryParams.search || '').trim().toLowerCase();
  const searchHash = rawSearch
    ? crypto.createHash('sha256').update(rawSearch).digest('hex').substring(0, 16)
    : '';

  // Canonical parameter map sorted deterministically
  const canonicalParams = {
    b: queryParams.bank_id || '',
    c: (queryParams.category || '').toLowerCase().trim(),
    cs: (queryParams.commission_status || '').toLowerCase().trim(),
    fd: queryParams.from_date || '',
    l: parseInt(queryParams.limit) || 25,
    m: queryParams.member_id || '',
    op: queryParams.operation_head_id || '',
    p: parseInt(queryParams.page) || 1,
    pb: (queryParams.process_by || '').toLowerCase().trim(),
    pid: queryParams.partner_id || '',
    pr: queryParams.product_id || '',
    sc: (queryParams.scope || '').toLowerCase().trim(),
    sh: searchHash,
    st: (queryParams.status || '').toLowerCase().trim(),
    td: queryParams.to_date || ''
  };

  const paramHash = crypto
    .createHash('sha256')
    .update(JSON.stringify(canonicalParams))
    .digest('hex')
    .substring(0, 16);

  // Scoped strictly to authenticated user identity and effective role
  return `app_list:${role}:${userId}:${paramHash}`;
}

/**
 * Retrieve cached applications response with bounded timeout
 * 
 * @param {string} cacheKey Cache key generated by buildApplicationListCacheKey
 * @returns {Promise<Object|null>} Cached payload or null
 */
async function getCachedApplicationList(cacheKey) {
  if (!cache.isEnabled()) return null;
  try {
    const cached = await cache.get(cacheKey);
    return cached || null;
  } catch (err) {
    logger.warn('[AppCache] Read warning (falling back to database):', err.message);
    return null;
  }
}

/**
 * Store application list response in cache
 * 
 * @param {string} cacheKey Cache key
 * @param {Object} payload Complete JSON response payload
 * @param {number} ttlSeconds Time to live in seconds (default 60s)
 * @returns {Promise<boolean>}
 */
async function setCachedApplicationList(cacheKey, payload, ttlSeconds = DEFAULT_APPLICATIONS_CACHE_TTL) {
  if (!cache.isEnabled() || !payload) return false;
  try {
    return await cache.set(cacheKey, payload, ttlSeconds);
  } catch (err) {
    logger.warn('[AppCache] Write warning:', err.message);
    return false;
  }
}

/**
 * Invalidate application list caches after successful database mutations.
 * Executes safely without blocking or throwing errors to callers.
 * 
 * @param {Object} metadata Contextual info for audit logging (no customer PII)
 * @returns {Promise<boolean>}
 */
async function invalidateApplicationsCache(metadata = {}) {
  try {
    if (!cache.isEnabled()) return false;
    
    // Pattern to invalidate all application list caches across all users and scopes
    const pattern = 'app_list:*';
    const ok = await cache.delPattern(pattern);
    logger.debug('[AppCache] Invalidated application list caches', {
      action: metadata.action || 'mutation',
      appId: metadata.appId || undefined,
      timestamp: new Date().toISOString()
    });
    return ok;
  } catch (err) {
    // Non-blocking: failure to invalidate cache must never abort a successful DB write
    logger.warn('[AppCache] Cache invalidation warning:', err.message);
    return false;
  }
}

module.exports = {
  DEFAULT_APPLICATIONS_CACHE_TTL,
  buildApplicationListCacheKey,
  getCachedApplicationList,
  setCachedApplicationList,
  invalidateApplicationsCache
};

